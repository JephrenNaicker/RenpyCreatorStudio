// cyrb53 – small, sync, non-cryptographic. Plenty for change detection.
export const hashString = (s: string, seed = 0): string => {
    let h1 = 0xdeadbeef ^ seed;
    let h2 = 0x41c6ce57 ^ seed;
    for (let i = 0; i < s.length; i++) {
        const ch = s.charCodeAt(i);
        h1 = Math.imul(h1 ^ ch, 2654435761);
        h2 = Math.imul(h2 ^ ch, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16);
};

// ─── Ren'Py literal / text helpers ───────────────────────────────────────────

// Plain Python/Ren'Py string literal (used for paths, names, choice labels).
const q = (s: string): string =>
    `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;

// Dialogue/menu text: also neutralise Ren'Py interpolation ([x]), text tags
// ({i}) and the legacy % formatting so user text is shown literally.
const textLiteral = (s: string): string =>
    q(s.replace(/%/g, '%%').replace(/\[/g, '[[').replace(/\{/g, '{{'));

const pyLiteral = (v: number | boolean | string): string => {
    if (typeof v === 'boolean') return v ? 'True' : 'False';
    if (typeof v === 'number') return String(v);
    return q(v);
};

const zeroFor = (t: 'number' | 'boolean' | 'string') =>
    t === 'number' ? '0' : t === 'boolean' ? 'False' : '""';

const fileSafe = (name: string): string => {
    const dot = name.lastIndexOf('.');
    const base = dot > 0 ? name.slice(0, dot) : name;
    const ext = dot > 0 ? name.slice(dot).toLowerCase().replace(/[^a-z0-9.]/g, '') : '';
    return `${slug(base)}${ext}`;
};

// ─── Compile context ─────────────────────────────────────────────────────────

export type VarType = 'number' | 'boolean' | 'string';

interface Ctx {
    input: ExportInput;
    issues: ExportIssue[];
    issueKeys: Set<string>;
    charById: Map<string, Character>;
    tagById: Map<string, string>;
    definedImages: Set<string>;
    backgrounds: Map<string, string>; // source path -> image name
    backgroundNames: Set<string>;
    transforms: Map<string, { name: string; lines: string[] }>;
    usedVars: Map<string, VarType>;
    registryKeys: Set<string>;
    jumps: { from: string; to: string; lineId?: string }[];
    warnedAssets: Set<string>;
}

const issue = (ctx: Ctx, i: ExportIssue) => {
    const key = `${i.code}|${i.sceneId ?? ''}|${i.lineId ?? ''}|${i.message}`;
    if (ctx.issueKeys.has(key)) return;
    ctx.issueKeys.add(key);
    ctx.issues.push(i);
};

const createCtx = (input: ExportInput): Ctx => {
    const ctx: Ctx = {
        input,
        issues: [],
        issueKeys: new Set(),
        charById: new Map(),
        tagById: new Map(),
        definedImages: new Set(),
        backgrounds: new Map(),
        backgroundNames: new Set(),
        transforms: new Map(),
        usedVars: new Map(),
        registryKeys: new Set((input.project.variables ?? []).map(v => v.key)),
        jumps: [],
        warnedAssets: new Set(),
    };

    const tags = resolveCharacterTags(input.characters, input.project.export_settings?.character_tags);
    for (const ch of input.characters) {
        ctx.charById.set(ch.id, ch);
        const { tag, deduped } = tags.get(ch.id)!;
        if (deduped) {
            issue(ctx, {
                severity: 'warning',
                code: 'duplicate_character_tag',
                message: `Character \"${ch.name}\" has the same script name (tag) as another character; using \"${tag}\" in the script.`,
            });
        }
        ctx.tagById.set(ch.id, tag);

        for (const o of ch.outfits ?? []) ctx.definedImages.add(`${tag} ${slug(o.name)}`);
        for (const e of ch.expressions ?? [])
            ctx.definedImages.add(`${tag} ${slug(e.outfit)} ${slug(e.name)}`);
    }

    for (const bg of input.project.background_assets ?? []) {
        registerBackground(ctx, bg.path, bg.name);
    }
    return ctx;
};

function registerBackground(ctx: Ctx, path: string, name?: string): string {
    const existing = ctx.backgrounds.get(path);
    if (existing) return existing;
    const hint = name || path.split('/').pop() || 'background';
    let candidate = `bg ${slug(hint.replace(/\.[a-z0-9]+$/i, ''))}`;
    let n = 2;
    while (ctx.backgroundNames.has(candidate)) candidate = `bg ${slug(hint)}_${n++}`;
    ctx.backgroundNames.add(candidate);
    ctx.backgrounds.set(path, candidate);
    return candidate;
}

// Project-level folder conventions (Setup & Exports) replace the built-in defaults.
function resolveFolder(ctx: Ctx, folder: string): string {
    const f = ctx.input.project.export_settings?.asset_folders;
    const custom = folder === 'images/bg' ? f?.backgrounds : folder === 'audio' ? f?.audio : f?.images;
    return cleanFolder(custom) ?? folder;
}

// folder = "images" | "images/bg" | "audio"
function assetPath(ctx: Ctx, source: string, folder: string, hint?: string, sceneId?: string, lineId?: string): string {
    const mapped = ctx.input.options.assetMap?.[source];
    if (mapped) return mapped;
    const dir = resolveFolder(ctx, folder);

    if (/^(blob:|data:|https?:)/.test(source)) {
        if (!ctx.warnedAssets.has(source)) {
            ctx.warnedAssets.add(source);
            issue(ctx, {
                severity: 'warning',
                code: 'asset_not_persisted',
                message: `"${hint ?? source.slice(0, 40)}" is a temporary upload (not a file path). It needs to be saved before the exported game can find it.`,
                sceneId,
                lineId,
            });
        }
        return `${dir}/${hint ? fileSafe(hint) : 'missing_asset'}`;
    }
    return source.includes('/') ? source : `${dir}/${source}`;
}

// ─── Positions / transforms ──────────────────────────────────────────────────

const hasRealTransform = (t?: TransformConfig): boolean =>
    !!t &&
    ((t.zoom !== undefined && t.zoom !== 1) ||
        !!t.rotate ||
        !!t.flip_x ||
        !!t.flip_y ||
        (t.alpha !== undefined && t.alpha !== 1) ||
        (!!t.blend && t.blend !== 'normal'));

interface PositionLike {
    position?: 'left' | 'center' | 'right' | 'custom';
    custom_x?: number;
    custom_y?: number;
    transform?: TransformConfig;
}

// Returns a Ren'Py `at` expression: a built-in (left/center/right) when
// possible, otherwise a generated named transform.
function positionName(ctx: Ctx, p: PositionLike): string {
    const pos = p.position ?? 'center';
    if (pos !== 'custom' && !hasRealTransform(p.transform)) return pos;

    const key = JSON.stringify([pos, p.custom_x, p.custom_y, p.transform ?? null]);
    const existing = ctx.transforms.get(key);
    if (existing) return existing.name;

    const name = `pos_${ctx.transforms.size + 1}`;
    // ASSUMPTION: custom_x / custom_y are 0–100 (percent of the screen).
    const xalign = pos === 'left' ? 0 : pos === 'right' ? 1 : pos === 'custom' ? (p.custom_x ?? 50) / 100 : 0.5;
    const yalign = pos === 'custom' ? (p.custom_y ?? 100) / 100 : 1;
    const t = p.transform ?? {};
    const lines = [`transform ${name}:`, `${INDENT}xalign ${xalign} yalign ${yalign}`];
    if (t.zoom !== undefined && t.zoom !== 1) lines.push(`${INDENT}zoom ${t.zoom}`);
    if (t.flip_x) lines.push(`${INDENT}xzoom -1.0`);
    if (t.flip_y) lines.push(`${INDENT}yzoom -1.0`);
    if (t.rotate) lines.push(`${INDENT}rotate ${t.rotate}`);
    if (t.alpha !== undefined && t.alpha !== 1) lines.push(`${INDENT}alpha ${t.alpha}`);
    if (t.blend && t.blend !== 'normal') lines.push(`${INDENT}blend ${q(t.blend)}`);
    ctx.transforms.set(key, { name, lines });
    return name;
}

// ─── Stage tracking ──────────────────────────────────────────────────────────
// `actors` is the logical state (who should be visible, how); `shown` is what
// Ren'Py currently has on screen. sync() diffs them and only emits show/hide
// when something changed. Ren'Py's `scene` statement clears the screen, so a
// background change calls clearScreen() and the next sync() re-shows everyone.

interface Actor {
    visible: boolean;
    outfit?: string;
    expression?: string;
    pos: string;
}

interface StagePatch extends PositionLike {
    action?: 'show' | 'hide';
    expression?: string;
    outfit?: string;
}

class Stage {
    private actors = new Map<string, Actor>();
    private shown = new Map<string, string>();

    constructor(private ctx: Ctx, private sceneId: string) { }

    private actor(id: string): Actor {
        let a = this.actors.get(id);
        if (!a) {
            a = { visible: false, pos: 'center' };
            this.actors.set(id, a);
        }
        return a;
    }

    apply(id: string, p: StagePatch) {
        const a = this.actor(id);
        if (p.action === 'hide') {
            a.visible = false;
            return;
        }
        a.visible = true;
        const ch = this.ctx.charById.get(id);
        if (p.expression) {
            a.expression = p.expression;
            const e = ch?.expressions?.find(x => x.name === p.expression);
            if (e?.outfit && !p.outfit) a.outfit = e.outfit;
        }
        if (p.outfit) a.outfit = p.outfit;
        if (!a.outfit && ch?.outfits?.length) a.outfit = ch.outfits[0]!.name;
        if (p.position) a.pos = positionName(this.ctx, p);
    }

    clearScreen() {
        this.shown.clear();
    }

    // The exact image if it exists, otherwise the closest one that does:
    //   1. outfit + expression (as requested)
    //   2. the outfit alone (keeps the outfit the author picked, drops a bad expression)
    //   3. the expression under the outfit it actually belongs to
    //   4. the character's first outfit
    // null when the character has no usable image at all.
    private resolveImage(id: string, tag: string, a: Actor, wanted: string): string | null {
        const defined = this.ctx.definedImages;
        if (defined.has(wanted)) return wanted;

        const ch = this.ctx.charById.get(id);
        const candidates: string[] = [];
        if (a.outfit) candidates.push(`${tag} ${slug(a.outfit)}`);
        const e = a.expression ? ch?.expressions?.find(x => x.name === a.expression) : undefined;
        if (e?.outfit) candidates.push(`${tag} ${slug(e.outfit)} ${slug(e.name)}`);
        const first = ch?.outfits?.[0];
        if (first) candidates.push(`${tag} ${slug(first.name)}`);

        return candidates.find(c => defined.has(c)) ?? null;
    }

    sync(ids?: Iterable<string>, lineId?: string): string[] {
        const out: string[] = [];
        for (const id of ids ?? Array.from(this.actors.keys())) {
            const a = this.actors.get(id);
            const tag = this.ctx.tagById.get(id);
            if (!a || !tag) continue;

            if (!a.visible) {
                if (this.shown.has(id)) {
                    out.push(`hide ${tag}`);
                    this.shown.delete(id);
                }
                continue;
            }

            const wanted = [tag, a.outfit && slug(a.outfit), a.expression && slug(a.expression)]
                .filter(Boolean)
                .join(' ');
            const name = this.resolveImage(id, tag, a, wanted);
            const key = `${name ?? wanted}@${a.pos}`;
            if (this.shown.get(id) === key) continue;

            if (name !== wanted) {
                // Ren'Py raises an exception for `show` on an image that doesn't exist, so a
                // warning alone isn't enough: show the closest valid image instead, or nothing.
                issue(this.ctx, {
                    severity: 'warning',
                    code: 'undefined_image',
                    message: name
                        ? `No image defined for "${wanted}" (check the outfit/expression pairing); showing "${name}" instead.`
                        : `No image defined for "${wanted}" and the character has no other images; nothing is shown.`,
                    sceneId: this.sceneId,
                    lineId,
                });
            }
            if (name) out.push(`show ${name} at ${a.pos}`);
            else out.push(`# skipped: no image for "${wanted}"`);
            this.shown.set(id, key);
        }
        return out;
    }
}

// ─── Statement compilers ─────────────────────────────────────────────────────

const noteVar = (ctx: Ctx, key: string, type: VarType, sceneId: string, lineId?: string) => {
    if (!ctx.usedVars.has(key)) ctx.usedVars.set(key, type);
    if (!ctx.registryKeys.has(key)) {
        issue(ctx, {
            severity: 'warning',
            code: 'undefined_variable',
            message: ctx.input.options.declareUndefinedVariables
                ? `Variable "${key}" isn't in the project's variable list. It will be auto-declared in variables.rpy.`
                : `Variable "${key}" isn't in the project's variable list; the game will crash when it is used.`,
            sceneId,
            lineId,
        });
    }
};

const effectStatement = (ctx: Ctx, fx: ChoiceEffect, sceneId: string, lineId: string): string => {
    const v = fx.variable;
    switch (fx.operation) {
        case 'add':
            noteVar(ctx, v, typeof fx.value === 'string' ? 'string' : 'number', sceneId, lineId);
            return `$ ${v} += ${pyLiteral(fx.value)}`;
        case 'subtract':
            noteVar(ctx, v, 'number', sceneId, lineId);
            return `$ ${v} -= ${pyLiteral(fx.value)}`;
        case 'toggle':
            noteVar(ctx, v, 'boolean', sceneId, lineId);
            return `$ ${v} = not ${v}`;
        case 'set':
        default:
            noteVar(ctx, v, typeof fx.value as VarType, sceneId, lineId);
            return `$ ${v} = ${pyLiteral(fx.value)}`;
    }
};

const buildCondition = (ctx: Ctx, c: MenuChoice, sceneId: string, lineId: string): string | undefined => {
    const parts = c._conditionParts;
    if (parts?.length) {
        return parts
            .map((p, i) => {
                noteVar(ctx, p.variable, typeof p.value as VarType, sceneId, lineId);
                const tail = i < parts.length - 1 ? ` ${p.logicalOp.toLowerCase()}` : '';
                return `${p.variable} ${p.operator} ${pyLiteral(p.value)}${tail}`;
            })
            .join(' ');
    }
    // Legacy data: best-effort translation of the stored string.
    // (Variables used only in legacy strings aren't tracked for auto-declare.)
    return c.condition
        ?.replace(/\btrue\b/g, 'True')
        .replace(/\bfalse\b/g, 'False')
        .replace(/&&/g, ' and ')
        .replace(/\|\|/g, ' or ')
        .trim() || undefined;
};

// Returns true when every choice jumps away (nothing after the menu is reachable).
function compileMenu(ctx: Ctx, scene: Scene, node: MenuNode, out: string[]): boolean {
    out.push('menu:');
    if (node.prompt?.trim()) out.push(`${INDENT}${textLiteral(node.prompt.trim())}`);

    for (const choice of node.choices) {
        const label = choice.text.trim();
        if (!label) {
            issue(ctx, {
                severity: 'warning',
                code: 'empty_choice',
                message: 'A menu choice has no text.',
                sceneId: scene.id,
                lineId: node.id,
            });
        }
        const cond = buildCondition(ctx, choice, scene.id, node.id);
        out.push(`${INDENT}${textLiteral(label || '(empty choice)')}${cond ? ` if ${cond}` : ''}:`);

        const body: string[] = (choice.effects ?? []).map(fx => effectStatement(ctx, fx, scene.id, node.id));
        if (choice.target_scene_id) {
            body.push(`jump ${sceneLabel(choice.target_scene_id)}`);
            ctx.jumps.push({ from: scene.id, to: choice.target_scene_id, lineId: node.id });
            if (choice.target_scene_id === scene.id) {
                issue(ctx, {
                    severity: 'info',
                    code: 'self_jump',
                    message: 'A choice jumps back to the start of its own scene (it can\'t target a specific line yet).',
                    sceneId: scene.id,
                    lineId: node.id,
                });
            }
        }
        if (!body.length) body.push('pass');
        body.forEach(l => out.push(`${INDENT}${INDENT}${l}`));
    }
    return node.choices.length > 0 && node.choices.every(c => !!c.target_scene_id);
}

function compileAction(ctx: Ctx, scene: Scene, node: ActionNode, stage: Stage, out: string[]) {
    if (node.action_type === 'background_change') {
        if (!node.background_path) {
            out.push('scene black');
        } else {
            out.push(`scene ${registerBackground(ctx, node.background_path, node.background_name)}`);
        }
        stage.clearScreen();
        out.push(...stage.sync(undefined, node.id)); // re-show everyone `scene` just cleared
        if (node.transition && node.transition !== 'instant') out.push(`with ${node.transition}`);
        return;
    }

    if (node.action_type === 'music_change') {
        const channel = node.music_label === 'Effect' ? 'sound' : 'music';
        const fade = node.music_fade && node.music_fade > 0 ? node.music_fade : 0;
        if (node.music_mode === 'stop') {
            out.push(`stop ${channel}${fade ? ` fadeout ${fade}` : ''}`);
        } else if (!node.music_path) {
            issue(ctx, {
                severity: 'warning',
                code: 'music_no_track',
                message: 'A music action is set to play but has no track selected.',
                sceneId: scene.id,
                lineId: node.id,
            });
        } else {
            const path = assetPath(ctx, node.music_path, 'audio', node.music_name, scene.id, node.id);
            out.push(`play ${channel} ${q(path)}${fade ? ` fadein ${fade}` : ''}`);
        }
    }
}

function compileDialogue(ctx: Ctx, scene: Scene, line: DialogueLine, stage: Stage, out: string[]) {
    const touched = new Set<string>();

    // Precedence: character_states first, then the speaker's own fields win.
    for (const cs of (line.character_states ?? []) as CharacterState[]) {
        stage.apply(cs.character_id, cs);
        touched.add(cs.character_id);
    }

    const speaker = line.character ? ctx.charById.get(line.character.id) : undefined;
    if (line.character && !speaker) {
        issue(ctx, {
            severity: 'warning',
            code: 'removed_character',
            message: `"${line.character.name}" isn't in the project roster; this line is exported as narration.`,
            sceneId: scene.id,
            lineId: line.id,
        });
    }
    if (speaker) {
        if (line.speaker_visible === false) {
            stage.apply(speaker.id, { action: 'hide' });
        } else {
            const ip: ImagePosition | undefined = line.image_position;
            stage.apply(speaker.id, {
                action: 'show',
                expression: line.expression,
                outfit: line.outfit,
                position: ip?.position,
                custom_x: ip?.custom_x,
                custom_y: ip?.custom_y,
                transform: ip?.transform,
            });
        }
        touched.add(speaker.id);
    }

    out.push(...stage.sync(touched, line.id));

    if (!line.text.trim()) {
        issue(ctx, {
            severity: 'info',
            code: 'empty_line',
            message: 'A dialogue line is empty and was skipped.',
            sceneId: scene.id,
            lineId: line.id,
        });
        return;
    }
    if (line.voice_path) {
        out.push(`voice ${q(assetPath(ctx, line.voice_path, 'audio', undefined, scene.id, line.id))}`);
    }
    const tag = speaker ? ctx.tagById.get(speaker.id) : undefined;
    out.push(`${tag ? `${tag} ` : ''}${textLiteral(line.text)}`);
}

function compileScene(ctx: Ctx, scene: Scene, nextSceneId: string | undefined): string[] {
    const out: string[] = [];
    const stage = new Stage(ctx, scene.id);
    const lines = scene.dialogue_lines ?? [];

    // The locked "initial background" line normally does this; backfill if absent.
    const first = lines[0];
    if (!(first?.type === 'action' && (first as ActionNode).is_initial)) out.push('scene black');

    let endsInJump = false;
    let warnedUnreachable = false;
    for (const line of lines) {
        if (endsInJump && !warnedUnreachable) {
            warnedUnreachable = true;
            // Every choice of the previous menu jumps away, so nothing from
            // here on can ever play. Report once, then keep emitting (valid Ren'Py).
            issue(ctx, {
                severity: 'warning',
                code: 'unreachable_after_menu',
                message: 'Lines after a menu where every choice jumps to another scene can never play.',
                sceneId: scene.id,
                lineId: line.id,
            });
        }
        endsInJump = false;
        if (line.type === 'menu') {
            endsInJump = compileMenu(ctx, scene, line as MenuNode, out);
        } else if (line.type === 'action') {
            compileAction(ctx, scene, line as ActionNode, stage, out);
        } else {
            compileDialogue(ctx, scene, line as DialogueLine, stage, out);
        }
    }

    if (!endsInJump) {
        if (ctx.input.options.sceneEnd === 'next_in_order' && nextSceneId) {
            out.push(`jump ${sceneLabel(nextSceneId)}`);
            ctx.jumps.push({ from: scene.id, to: nextSceneId });
        } else {
            out.push('return');
        }
    }
    return out;
}

// ─── Emitters ────────────────────────────────────────────────────────────────

const emitScene = (scene: Scene, body: string[]): string =>
    [
        HEADER,
        `# Scene: ${scene.name.replace(/\s+/g, ' ')}`,
        `label ${sceneLabel(scene.id)}:`,
        ...body.map(l => INDENT + l),
        '',
    ].join('\n');

const emitCharacters = (ctx: Ctx): string =>
    [
        HEADER,
        '',
        ...ctx.input.characters.map(
            ch => `define ${ctx.tagById.get(ch.id)} = Character(${q(ch.name)}, color=${q(ch.color)})`
        ),
        '',
    ].join('\n');

const emitImages = (ctx: Ctx): string => {
    const lines: string[] = [HEADER, '', '# Character sprites'];
    for (const ch of ctx.input.characters) {
        const tag = ctx.tagById.get(ch.id)!;
        for (const o of ch.outfits ?? []) {
            lines.push(`image ${tag} ${slug(o.name)} = ${q(assetPath(ctx, o.default_image, 'images', o.default_image))}`);
        }
        for (const e of ch.expressions ?? []) {
            lines.push(`image ${tag} ${slug(e.outfit)} ${slug(e.name)} = ${q(assetPath(ctx, e.image_path, 'images', e.image_path))}`);
        }
    }
    if (ctx.backgrounds.size) {
        lines.push('', '# Backgrounds');
        ctx.backgrounds.forEach((name, path) => {
            lines.push(`image ${name} = ${q(assetPath(ctx, path, 'images/bg', name.replace(/^bg /, '')))}`);
        });
    }
    if (ctx.transforms.size) {
        lines.push('', '# Positions');
        ctx.transforms.forEach(t => lines.push(...t.lines, ''));
    }
    return lines.join('\n') + '\n';
};

const emitVariables = (ctx: Ctx): string => {
    const lines: string[] = [HEADER, ''];
    for (const v of ctx.input.project.variables ?? []) {
        lines.push(`default ${v.key} = ${pyLiteral(v.default_value)}`);
    }
    if (ctx.input.options.declareUndefinedVariables) {
        const extra = Array.from(ctx.usedVars.entries()).filter(([k]) => !ctx.registryKeys.has(k));
        if (extra.length) {
            lines.push('', '# Used in scenes but missing from the project variable list:');
            extra.sort(([a], [b]) => a.localeCompare(b));
            extra.forEach(([k, t]) => lines.push(`default ${k} = ${zeroFor(t)}`));
        }
    }
    return lines.join('\n') + '\n';
};

const emitScript = (startSceneId: string): string =>
    [HEADER, '', 'label start:', `${INDENT}jump ${sceneLabel(startSceneId)}`, ''].join('\n');

const emitStubs = (ids: string[]): string =>
    [
        '# Placeholders for scenes that were not part of this export.',
        '# Delete a stub once the real scene file is in your game folder.',
        '',
        ...ids.sort().flatMap(id => [`label ${sceneLabel(id)}:`, `${INDENT}return`, '']),
    ].join('\n');

// ─── Entry point ─────────────────────────────────────────────────────────────

function runExport(input: ExportInput): ExportResult & { ctx: Ctx } {
    const { options } = input;
    const ctx = createCtx(input);
    const selected = new Set(options.sceneIds);
    const knownScenes = new Set(input.scenes.map(s => s.id));

    // 1. Compile every scene so shared output is selection-independent.
    const bodies = new Map<string, string[]>();
    input.scenes.forEach((scene, i) => {
        bodies.set(scene.id, compileScene(ctx, scene, input.scenes[i + 1]?.id));
    });

    if (options.startSceneId) {
        ctx.jumps.push({ from: START, to: options.startSceneId });
    }

    // 2. Dangling-jump pass (only for jumps that originate in exported files).
    const missing = new Set<string>();
    for (const j of ctx.jumps) {
        if (j.from !== START && !selected.has(j.from)) continue;
        const sceneId = j.from === START ? undefined : j.from;
        if (!knownScenes.has(j.to)) {
            issue(ctx, {
                severity: 'error',
                code: 'unknown_scene',
                message: `Jump to scene "${j.to}", which doesn't exist in this project.`,
                sceneId,
                lineId: j.lineId,
            });
        } else if (!selected.has(j.to)) {
            missing.add(j.to);
            const target = input.scenes.find(s => s.id === j.to)!;
            issue(ctx, {
                severity: options.stubMissingScenes ? 'info' : 'error',
                code: 'dangling_jump',
                message: options.stubMissingScenes
                    ? `Jumps to "${target.name}", which isn't selected. A placeholder label will be generated.`
                    : `Jumps to "${target.name}", which isn't selected. The game will fail at that jump.`,
                sceneId,
                lineId: j.lineId,
            });
        }
    }

    // 3. Emit.
    const files: ExportFile[] = [];
    const add = (path: string, content: string, kind: ExportFile['kind'], sceneId?: string) =>
        files.push({ path, content, kind, sceneId, hash: hashString(content) });

    if (options.includeShared) {
        add(SHARED_PATHS.characters, emitCharacters(ctx), 'shared');
        add(SHARED_PATHS.images, emitImages(ctx), 'shared');
        add(SHARED_PATHS.variables, emitVariables(ctx), 'shared');
    }
    if (options.startSceneId) add(SHARED_PATHS.script, emitScript(options.startSceneId), 'shared');

    for (const scene of input.scenes) {
        if (selected.has(scene.id)) add(scenePath(scene.id), emitScene(scene, bodies.get(scene.id)!), 'scene', scene.id);
    }
    if (options.stubMissingScenes && missing.size) {
        add(SHARED_PATHS.stubs, emitStubs(Array.from(missing)), 'stub');
    }

    const rank: Record<IssueSeverity, number> = { error: 0, warning: 1, info: 2 };
    const issues = ctx.issues
        .filter(i => !i.sceneId || selected.has(i.sceneId))
        .sort((a, b) => rank[a.severity] - rank[b.severity]);

    return { files, issues, ctx };
}

export function exportProject(input: ExportInput): ExportResult {
    const { files, issues } = runExport(input);
    return { files, issues };
}

// ─── Project defaults & shared-files preview ─────────────────────────────────
// ExportSettings (Project.export_settings, edited in Setup & Exports) holds what
// is true for the whole project. ExportOptions is what one export run uses; it
// starts from these defaults and the export dialog may override it per run.

export function optionsFromSettings(settings?: ExportSettings | null): Partial<ExportOptions> {
    return {
        sceneEnd: settings?.scene_end ?? DEFAULT_EXPORT_OPTIONS.sceneEnd,
        stubMissingScenes: settings?.stub_missing_scenes ?? DEFAULT_EXPORT_OPTIONS.stubMissingScenes,
        declareUndefinedVariables:
            settings?.declare_undefined_variables ?? DEFAULT_EXPORT_OPTIONS.declareUndefinedVariables,
    };
}

export interface UndeclaredVariable {
    key: string;
    type: VarType;
}

export interface SharedExportResult extends ExportResult {
    // Used by choices/conditions but missing from the project's variable list.
    undeclaredVariables: UndeclaredVariable[];
}

// characters.rpy / images.rpy / variables.rpy exactly as the export dialog would
// produce them with the project defaults. Shared files depend on every scene
// (backgrounds, positions, variables), so scenes are still required.
export function exportSharedFiles(
    input: Omit<ExportInput, 'options'> & { options?: Partial<ExportOptions> }
): SharedExportResult {
    const { files, issues, ctx } = runExport({
        ...input,
        options: {
            ...DEFAULT_EXPORT_OPTIONS,
            ...optionsFromSettings(input.project.export_settings),
            ...input.options,
            sceneIds: [],
            includeShared: true,
            startSceneId: undefined,
            stubMissingScenes: false,
        },
    });

    const undeclaredVariables = Array.from(ctx.usedVars.entries())
        .filter(([key]) => !ctx.registryKeys.has(key))
        .map(([key, type]) => ({ key, type }))
        .sort((a, b) => a.key.localeCompare(b.key));

    return { files: files.filter(f => f.kind === 'shared'), issues, undeclaredVariables };
}

// ─── Export tracking ─────────────────────────────────────────────────────────

// Status of every trackable file in the project (scene files + shared files).
// Run this for sidebar badges; look scenes up with scenePath(scene.id).
export function getExportStatuses(input: ExportInput, records: ExportRecords): Record<string, FileStatus> {
    const { files } = exportProject({
        ...input,
        options: {
            ...input.options,
            sceneIds: input.scenes.map(s => s.id),
            includeShared: true,
            stubMissingScenes: false,
        },
    });
    const result: Record<string, FileStatus> = {};
    for (const f of files) {
        const r = records[f.path];
        result[f.path] = !r
            ? { status: 'never' }
            : { status: r.hash === f.hash ? 'up_to_date' : 'changed', exported_at: r.exported_at };
    }
    return result;
}

// Call when the user actually clicks Download. Returns a new records object
// (stubs are never tracked, they depend on the selection).
export function recordExport(
    records: ExportRecords,
    files: ExportFile[],
    at: string = new Date().toISOString()
): ExportRecords {
    const next = { ...records };
    for (const f of files) {
        if (f.kind === 'stub') continue;
        next[f.path] = { path: f.path, hash: f.hash, exported_at: at };
    }
    return next;
}