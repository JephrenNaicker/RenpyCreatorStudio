// frontend/src/services/renpyExportService.ts
//
// Pure, UI-free Ren'Py exporter. No Vue, no fetch, no Date.now() inside the
// generated text (timestamps would change every hash and break "changed since
// export" tracking).
//
// Pipeline (all in exportProject):
//   1. compile  – walk EVERY scene in the project (so shared files such as
//                 images.rpy / variables.rpy never depend on the selection)
//   2. validate – issues are collected while compiling + a dangling-jump pass
//   3. emit     – build files only for the selected scenes (+ shared files)
//
// Export tracking: every file gets a content hash. The UI stores an
// ExportRecord per path when the user downloads, and getExportStatuses()
// compares fresh hashes to those records.

